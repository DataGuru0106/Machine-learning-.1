# necessary libraries
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt

from  sklearn.datasets import load_iris

iris = load_iris() # Iris flower dataset

# creat Datafram
data = pd.DataFrame(iris.data, columns=iris.feature_names) # feature

# Add target column
data['species'] = iris.target
print(data.head()) # first 5 record printed

"""2) Data Collection And EDA"""

data.shape # ( rows, columns)

data.info() # Strcture of data

# Target Class Distribution
data['species'].value_counts() # 0= setosa , 1 = versicolor,2=virginica

# Scatter plot
plt.scatter(data['petal length (cm)'],data['petal width (cm)'],c=data['species'])
plt.xlabel('Petal Length')
plt.ylabel('Petal Width')
plt.title('Scatter Plot of Petal Length vs Petal Width')
plt.show()

data.boxplot()
plt.show()

# Data Splitting
x=data.iloc[:, :4] # Independent Variable
y=data.iloc[:, -1] # Dependent variable

y.head()

# data splitting
from sklearn.model_selection import train_test_split
x_train,x_test,y_train,y_test=train_test_split(x,y,test_size=0.2,random_state=42) # Test data=
x_train.head()

"""3] Model Building"""

# create Dicision tree model
from sklearn.tree import DecisionTreeClassifier
model=DecisionTreeClassifier(max_depth=3,random_state=42)
model.fit(x_train,y_train) # train model

# predict test data
y_pred=model.predict(x_test)
y_pred[:10]

# Classificatin Metrics
from sklearn.metrics import accuracy_score, precision_score, recall_score, f1_score

print("Train-Teat Split Result    ")
print("Accuracy:",accuracy_score(y_test,y_pred))
print("Precision:",precision_score(y_test,y_pred,average='weighted'))
print("Recall:",recall_score(y_test,y_pred,average='weighted'))
print("F1 Score :", f1_score(y_test,y_pred,average='weighted'))

"""K-Fold Cross Validation
Creat K Fold
k-1 fold for Training and remaining fold for for testing
"""

#6. 5-fold cross validation
from sklearn.model_selection import cross_validate, KFold


kf = KFold(n_splits=5, shuffle=True, random_state=42)
results = cross_validate( model, x, y, cv=kf,
                      scoring = ["accuracy",
             "precision_weighted",
             "recall_weighted",
            "f1_weighted"])

# Average K-fold Result
print("\n5-Fold Cross Validation Result    ")
print("Accuracy:",np.mean(results["test_accuracy"]))
print("Precision:",np.mean(results["test_precision_weighted"]))
print("Recall:",np.mean(results["test_recall_weighted"]))
print("F1 Score :", np.mean(results["test_f1_weighted"]))