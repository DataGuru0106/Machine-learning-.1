"""5] Train-test spkit"""

from sklearn.model_selection import train_test_split
X_train,X_test,Y_train,Y_test= train_test_split(X,Y,test_size=0.3,random_state=42)
# test data =30% training data =70%

"""6] model training & evaluation (linear kernal )"""

# Linear Classifier
from sklearn.svm import SVC
liner_svm = SVC(kernel="linear")
liner_svm.fit(X_train,Y_train)

from sklearn.metrics import accuracy_score
Y_pred = liner_svm.predict(X_test)
print("Linear SVM Accuracy:", accuracy_score(Y_test, Y_pred))

"""Model Training (RBF Kernel)"""

# RBF SVM
rbf_svm = SVC(kernel='rbf', C=10, gamma='scale')
rbf_svm.fit(X_train, Y_train)

Y_pred_rbf = rbf_svm.predict(X_test)
print("RBF SVM Accuracy:", accuracy_score(Y_test, Y_pred_rbf))

"""8]Model Training (polynomial kernal )"""

# polynomial SVM
poly_svm = SVC(kernel='poly', degree=3, C=1)
poly_svm.fit(X_train, Y_train)
Y_pred_poly = poly_svm.predict(X_test)
print("Polynomial SVM Accuracy:", accuracy_score(Y_test, Y_pred_poly))

"""9] Hyperparameter Tuning via Grid Search"""

# Hyperparameter tuning
from sklearn.model_selection import GridSearchCV

params = {
    'C': [0.1, 1, 10, 100],
    'gamma': ['scale', 0.1, 0.01, 0.001]
}

grid = GridSearchCV(SVC(kernel='rbf'), params, cv=5, scoring='accuracy')
grid.fit(X_train, Y_train)
print("\nBest parameters:")
print(grid.best_params_)

"""IO] Evaluate Best Tuned Model"""

# best model
from sklearn.metrics import accuracy_score, classification_report

best_model = grid.best_estimator_
Y_pred_best = best_model.predict(X_test)

print("\nTuned RBF SVM Accuracy:", accuracy_score(Y_test, Y_pred_best))
print("\nClassification Report:")
print(classification_report(Y_test, Y_pred_best))