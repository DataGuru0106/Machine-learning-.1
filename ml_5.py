import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns
from sklearn.svm import SVC

"""2] Load and preview Dataset"""

df = pd.read_csv("Non_linear_SVM_Dataset.csv")
df

df.info() #Structure of Data

"""3] Feature and Target Splitting"""

from re import X
Y = df["Y"] # output
X = df.drop(columns=["Y"]) # input
X.head()

"""4] Exploaratory Data Analysis ans Visualization"""

# Assuming X1 and X2 are the first two column of X
plt.figure(figsize=(8, 6))
plt.scatter(X.iloc[:, 0], X.iloc[:, 1], c=Y, cmap='viridis')
plt.xlabel('X1')
plt.ylabel('X2')
plt.title('Scatter Plot of X1 vs X2')

from mpl_toolkits.mplot3d import Axes3D
#mpl_toolkits.mplot3d is a tookit adds 3D plotting capabillities to Matplolob
fig = plt.figure(figsize=(8, 6))
ax = fig.add_subplot(111, projection='3d')
ax.scatter (X['X1'], X['X2'], Y,c=Y, cmap='viridis')
